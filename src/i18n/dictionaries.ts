export const dictionaries = { en, vi } as const;

export function translate(
  dict: Dictionary,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let s = dict[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
